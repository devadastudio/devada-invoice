                      type="button"
                      onClick={handleSyncWithSettingsFooter}
                      className="text-[10px] text-blue-600 dark:text-blue-400 font-semibold hover:underline flex items-center gap-1 self-start sm:self-auto py-1 px-2 rounded-lg bg-blue-50/60 dark:bg-blue-950/40 border border-blue-200/50 dark:border-blue-900/30 transition-colors"
